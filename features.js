window._resolvedImageMemory = window._resolvedImageMemory || {};

async function resolvePlacePhoto(placeName, districtName) {
    const memKey = `${placeName}_${districtName}`;
    if (window._resolvedImageMemory[memKey] !== undefined) {
        return window._resolvedImageMemory[memKey];
    }

    try {
        // Step A: District Context ke sath direct search query
        const searchUrl = `https://en.wikipedia.org/w/api.php?action=query&format=json&origin=*&generator=search&gsrsearch=${encodeURIComponent(placeName + ' ' + districtName)}&gsrlimit=1&prop=pageimages&pithumbsize=600`;
        const res = await fetch(searchUrl);
        const data = await res.json();

        if (data && data.query && data.query.pages) {
            const pages = data.query.pages;
            const firstId = Object.keys(pages)[0];
            if (firstId && pages[firstId].thumbnail && pages[firstId].thumbnail.source) {
                const liveImg = pages[firstId].thumbnail.source;
                window._resolvedImageMemory[memKey] = liveImg;
                return liveImg;
            }
        }

        // Step B: Sirf jagah ke naam se direct lookup
        const directUrl = `https://en.wikipedia.org/w/api.php?action=query&format=json&origin=*&titles=${encodeURIComponent(placeName)}&prop=pageimages&pithumbsize=600`;
        const res2 = await fetch(directUrl);
        const data2 = await res2.json();

        if (data2 && data2.query && data2.query.pages) {
            const pages2 = data2.query.pages;
            const secondId = Object.keys(pages2)[0];
            if (secondId && pages2[secondId].thumbnail && pages2[secondId].thumbnail.source) {
                const liveImg = pages2[secondId].thumbnail.source;
                window._resolvedImageMemory[memKey] = liveImg;
                return liveImg;
            }
        }
    } catch (e) {
        console.warn("Wiki resolver skipped:", placeName);
    }

    window._resolvedImageMemory[memKey] = null;
    return null;
}

